-- "Videoya soru sor" özelliğinin altyapısı.
-- Akış: video yüklenir -> Whisper sesi yazıya çevirir (transcript_segments)
--       -> yazı 30-60 sn'lik parçalara bölünür, her parça 768 sayılık vektöre çevrilir (vector_store)
--       -> soru gelince sorunun vektörüne en yakın parçalar bulunur.

-- Vektör sütunu ve "en yakını bul" sorgusu için eklenti (imaj: pgvector/pgvector)
CREATE EXTENSION IF NOT EXISTS vector;

-- Her videonun transkript durumu: PENDING (beklemede), PROCESSING (işleniyor), READY (hazır), FAILED (hata)
CREATE TABLE video_transcripts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id      bigint       NOT NULL UNIQUE REFERENCES videos(id) ON DELETE CASCADE,
    status        varchar(20)  NOT NULL,
    language      varchar(10),
    error_message varchar(500),
    created_at    timestamp(6),
    updated_at    timestamp(6)
);

-- Whisper'ın çıkardığı zaman damgalı cümleler (ham hâliyle saklanır:
-- parça boyu değişirse Whisper'ı yeniden çalıştırmadan yeniden parçalanabilsin)
CREATE TABLE transcript_segments (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id      bigint           NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    start_seconds double precision NOT NULL,
    end_seconds   double precision NOT NULL,
    text          varchar(2000)    NOT NULL
);
CREATE INDEX idx_transcript_segments_video ON transcript_segments (video_id, start_seconds);

-- Parçalar ve vektörleri. Yapı Spring AI'ın PgVectorStore'unun beklediği şekilde:
-- metadata'da videoId, başlangıç ve bitiş saniyesi tutulur.
-- Videoya yabancı anahtarla bağlı değil (Spring AI'ın tablosu); video silinince kod temizler (2c).
CREATE TABLE vector_store (
    id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    content   text,
    metadata  json,
    embedding vector(768)
);
-- HNSW: kitabın dizini gibi, binlerce parçaya tek tek bakmadan en yakınları bulur (kosinüs uzaklığı)
CREATE INDEX idx_vector_store_embedding ON vector_store USING hnsw (embedding vector_cosine_ops);
