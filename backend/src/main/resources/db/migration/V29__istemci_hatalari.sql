-- Tarayıcıda olan beklenmedik hatalar (hata yakalayıcı ekranı, yakalanmamış JavaScript hatası).
-- Kullanıcı bize yazmadan sorunu görmek için: yönetim panelinde "Hatalar" sekmesi. 30 günden eskiler silinir.
CREATE TABLE client_errors (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message    varchar(500)  NOT NULL,
    stack      varchar(4000),
    page_url   varchar(500),
    user_agent varchar(300),
    -- Hesap silinirse hata kaydı kalır, kimin gördüğü kalmaz
    user_id    bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX idx_client_errors_time ON client_errors (created_at DESC);
CREATE INDEX idx_client_errors_user ON client_errors (user_id);
