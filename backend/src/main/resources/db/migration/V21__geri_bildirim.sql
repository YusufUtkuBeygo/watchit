-- "Geri bildirim gönder": kullanıcının site hakkında yazdığı not (YouTube sol menüsündeki gibi).
-- Hesap silinince bildirimi kalır ama kime ait olduğu boşalır (geri bildirim ürünün malı, kişisel veri değil).
CREATE TABLE feedback (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint REFERENCES users (id) ON DELETE SET NULL,
    message    varchar(2000) NOT NULL,
    page_url   varchar(255),
    created_at timestamp(6)  NOT NULL
);
CREATE INDEX idx_feedback_user ON feedback (user_id, created_at DESC);
