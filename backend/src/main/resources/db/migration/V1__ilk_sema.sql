    CONSTRAINT fkdv2gmwgbah9oic0gfp0ugdge FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fkqkle8cmswdq5k364lgf5feyr3 FOREIGN KEY (video_id) REFERENCES videos (id)
);
