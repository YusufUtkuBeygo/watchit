-- Hesabın e-postası doğrulandı mı. Doğrulanmamış hesap siteyi gezer ama video yükleyemez, yorum yazamaz.
ALTER TABLE users ADD COLUMN email_verified boolean NOT NULL DEFAULT false;
-- Var olan hesaplar (demo, test) bu özellikten önce açıldı: doğrulanmış sayılır, kimse kilitlenmesin.
UPDATE users SET email_verified = true;

-- Şifre en son ne zaman değişti. Bundan ÖNCE verilmiş giriş anahtarları (JWT) artık kabul edilmez.
ALTER TABLE users ADD COLUMN password_changed_at timestamp(6);

-- Tek kullanımlık kodlar ve bağlantılar. Kodun kendisi değil, hash'i saklanır (veritabanı sızsa bile kullanılamasın).
CREATE TABLE email_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     varchar(20)  NOT NULL,              -- VERIFY_EMAIL ya da RESET_PASSWORD
    token_hash  varchar(64)  NOT NULL,              -- HMAC-SHA256 / SHA-256, 64 hex karakter
    expires_at  timestamp(6) NOT NULL,
    used_at     timestamp(6),                       -- doluysa kullanıldı ya da iptal edildi
    attempts    integer      NOT NULL DEFAULT 0,    -- yanlış kod denemeleri
    created_at  timestamp(6) NOT NULL
);
CREATE INDEX idx_email_tokens_user ON email_tokens (user_id, purpose, created_at DESC);
CREATE INDEX idx_email_tokens_hash ON email_tokens (token_hash);
