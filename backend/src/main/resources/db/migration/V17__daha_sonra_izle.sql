-- "Daha sonra izle" listesi: kullanıcı bir videoyu sonra izlemek üzere kaydeder.
-- Aynı video bir kullanıcının listesinde bir kez olur; kullanıcı ya da video silinince kayıt da gider.
CREATE TABLE watch_later (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    video_id   bigint    NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_watch_later_user_video UNIQUE (user_id, video_id)
);
CREATE INDEX idx_watch_later_user ON watch_later (user_id, created_at DESC);
