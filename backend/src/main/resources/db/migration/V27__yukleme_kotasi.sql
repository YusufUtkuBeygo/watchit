-- Yükleme kotası.
-- videos.size_bytes: kullanıcının yüklediği asıl dosyanın boyutu (video kaydı oluşturulurken MinIO'dan okunur).
-- Toplam kota bunların toplamına bakar; video silinince yer boşalır. Eski videolarda boş (kotaya sayılmaz).
ALTER TABLE videos ADD COLUMN size_bytes bigint CHECK (size_bytes >= 0);

-- Yükleme defteri: her imzalı yükleme adresi verildiğinde tarayıcının bildirdiği boyut yazılır.
-- Günlük kota son 24 saatin toplamına bakar (dosya videoya bağlanmasa da sayılır: sahipsiz dosyayla depo şişirilemesin).
CREATE TABLE upload_reservations (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    bytes      bigint    NOT NULL CHECK (bytes > 0),
    created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX idx_upload_reservations_user_time ON upload_reservations (user_id, created_at);
