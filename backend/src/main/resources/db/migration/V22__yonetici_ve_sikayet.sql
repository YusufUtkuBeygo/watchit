-- Yönetici rolü ve şikayetler.
-- Rol: USER (herkes) ya da ADMIN. Yönetici sitede atanmaz, veritabanından verilir:
--   UPDATE users SET role = 'ADMIN' WHERE email = '...';
ALTER TABLE users ADD COLUMN role varchar(20) NOT NULL DEFAULT 'USER';
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'));

-- Şikayet: bir kullanıcı bir videoyu ya da yorumu bildirir, yönetici inceler.
-- target_id yabancı anahtar değil (video da olabilir yorum da): içerik silinince şikayet kayıt olarak kalır.
-- Şikayet eden hesabını silerse şikayet kalır, kimin yaptığı boşalır.
CREATE TABLE reports (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id bigint REFERENCES users (id) ON DELETE SET NULL,
    target_type varchar(20)   NOT NULL CHECK (target_type IN ('VIDEO', 'COMMENT')),
    target_id   bigint        NOT NULL,
    reason      varchar(30)   NOT NULL CHECK (reason IN ('SPAM', 'HARASSMENT', 'HATE', 'VIOLENCE', 'SEXUAL', 'MISLEADING', 'COPYRIGHT', 'OTHER')),
    details     varchar(1000),
    status      varchar(20)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    created_at  timestamp(6)  NOT NULL,
    resolved_at timestamp(6),
    resolved_by bigint REFERENCES users (id) ON DELETE SET NULL
);
-- Aynı kişi aynı içeriği bir kez şikayet eder (ikinci kez 409)
CREATE UNIQUE INDEX uk_reports_reporter_target ON reports (reporter_id, target_type, target_id);
CREATE INDEX idx_reports_status ON reports (status, created_at DESC);
CREATE INDEX idx_reports_target ON reports (target_type, target_id);

-- Yönetici içeriği kaldırınca sahibine bildirim gider: yeni bildirim türü SYSTEM
ALTER TABLE notifications DROP CONSTRAINT notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_type_check
    CHECK (type IN ('LIKE', 'COMMENT', 'SUBSCRIBE', 'VIDEO_UPLOAD', 'SYSTEM'));
