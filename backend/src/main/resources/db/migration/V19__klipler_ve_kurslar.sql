-- Klipler: kullanıcı bir videonun 5-60 saniyelik bir parçasını adıyla kaydeder (YouTube "Klipler").
-- Kullanıcı ya da video silinince klip de gider.
CREATE TABLE clips (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    video_id      bigint       NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    title         varchar(140) NOT NULL,
    start_seconds integer      NOT NULL CHECK (start_seconds >= 0),
    end_seconds   integer      NOT NULL,
    created_at    timestamp(6) NOT NULL,
    -- Aynı kural serviste de var; burada son savunma hattı: süre 5-60 sn
    CONSTRAINT ck_clips_length CHECK (end_seconds - start_seconds BETWEEN 5 AND 60)
);
CREATE INDEX idx_clips_user ON clips (user_id, created_at DESC);

